CREATE TABLE [Преподаватели] (
  [Код преподавателя] LONG NOT NULL,
  [Фамилия] TEXT(15) NOT NULL,
  [Имя] TEXT(13) NOT NULL,
  [Отчество] TEXT(15),
  [Дата рождения] DATETIME,
  [Должность] TEXT(25),
  [Стаж] LONG,
  [Кафедра] TEXT(11),
  [Телефон] TEXT(9),
  [Зарплата] CURRENCY,
  CONSTRAINT [PK_Преподаватели] PRIMARY KEY ([Код преподавателя])
);

CREATE TABLE [Студенты] (
  [Код студента] LONG NOT NULL,
  [Фамилия] TEXT(15),
  [Имя] TEXT(12),
  [Отчество] TEXT(15),
  [Номер группы] LONG,
  [Адрес] TEXT(30),
  [Телефон] TEXT(9),
  [Медалист] YESNO,
  CONSTRAINT [PK_Студенты] PRIMARY KEY ([Код студента])
);

CREATE TABLE [Дисциплины] (
  [Код дисциплины] LONG NOT NULL,
  [Название дисциплины] TEXT(30),
  [Номер семестра] LONG,
  [Код преподавателя] LONG NOT NULL,
  [Экзамен] TEXT(3),
  CONSTRAINT [PK_Дисциплины] PRIMARY KEY ([Код дисциплины]),
  CONSTRAINT [FK_Дисциплины_Преподаватели]
    FOREIGN KEY ([Код преподавателя])
    REFERENCES [Преподаватели]([Код преподавателя])
);

CREATE TABLE [Оценки] (
  [Код студента] LONG NOT NULL,
  [Код дисциплины] LONG NOT NULL,
  [Номер семестра] LONG NOT NULL,
  [Оценка] LONG,
  CONSTRAINT [PK_Оценки] PRIMARY KEY ([Код студента], [Код дисциплины], [Номер семестра]),
  CONSTRAINT [FK_Оценки_Студенты]
    FOREIGN KEY ([Код студента])
    REFERENCES [Студенты]([Код студента]),
  CONSTRAINT [FK_Оценки_Дисциплины]
    FOREIGN KEY ([Код дисциплины])
    REFERENCES [Дисциплины]([Код дисциплины])
);

